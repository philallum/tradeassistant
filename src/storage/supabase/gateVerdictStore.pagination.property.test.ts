// Property test for SupabaseGateVerdictStore.getVerdict() paginated fold reads
// (dashboard-data-activation Task 1.5; design Component 1).
//
// Feature: dashboard-data-activation, Property 3: Paginated reads return the complete set
//
// Property 3 asserts that when a verdict's `gate_fold_verdicts` set spans MORE
// THAN ONE PostgREST page (> 1000 rows), `getVerdict` returns EVERY fold row —
// never truncated at the ~1000-row hosted-gateway ceiling — by exercising the
// `SupabaseRestClient.select` Range / Content-Range paging loop
// (SELECT_PAGE_SIZE = 1000) against a no-network stub `fetch`.
//
// The stub below is the authoritative model of the server the real adapter
// talks to: it stores one aggregate verdict row plus a fold-row set whose size
// is generated by fast-check across a range that CROSSES the page boundary
// (1001..2200), and it serves GET selects by honoring the `Range` request
// header — returning only the requested slice and setting a correct
// `Content-Range: start-end/total`, replying 206 for a partial page and 200 for
// a complete single page. The aggregate `id=eq.<id>&limit=1` select returns the
// single aggregate row. If the adapter failed to page, it would read only the
// first ~1000 fold rows and this property would fail.
//
// **Validates: Requirements 1.7**

import { describe, expect, it } from "vitest";
import fc from "fast-check";

import type { SupabaseConfig } from "../supabaseConfig.js";
import { SupabaseRestClient } from "./client.js";
import { SupabaseGateVerdictStore } from "./gateVerdictStore.js";

const CONFIG: SupabaseConfig = {
  target: "hosted",
  url: "https://proj.supabase.co",
  key: "scoped-write-jwt",
  apiKey: "sb_publishable_anon",
};

/** The server page size the real client pages with (SELECT_PAGE_SIZE). */
const PAGE_SIZE = 1000;

const VERDICT_ID = "verdict-paged";

/**
 * One aggregate `gate_verdicts` row with the shape the adapter's `fromVerdictRow`
 * reconstructs from. The specific gate values are irrelevant to pagination —
 * this property only cares about the completeness of the fold-row set — so a
 * fixed, valid CUT aggregate is used.
 */
function aggregateRow(): Record<string, unknown> {
  return {
    id: VERDICT_ID,
    config_id: "EURUSD-active",
    sample_size: 500,
    gate1_model_acc: 0.6,
    gate1_baseline_acc: 0.5,
    gate1_delta_pp: 0.1,
    gate1_passed: true,
    gate2_model_ra: null,
    gate2_baseline_ra: null,
    gate2_margin: null,
    gate2_passed: null,
    verdict: "CUT",
    selected_horizon: null,
    split_train_end: "2020-01-01",
    split_test_start: "2020-01-02",
    split_test_end: "2020-12-31",
  };
}

/**
 * Build the full `gate_fold_verdicts` row set for `total` folds, with
 * contiguous `fold_index` 0..total-1 and the `metrics` jsonb each fold's
 * reconstruction needs.
 */
function foldRows(total: number): Record<string, unknown>[] {
  const rows: Record<string, unknown>[] = [];
  for (let i = 0; i < total; i += 1) {
    rows.push({
      verdict_id: VERDICT_ID,
      fold_index: i,
      sample_size: 42,
      skipped: false,
      gate1_passed: true,
      gate2_passed: null,
      verdict: "PASS",
      metrics: {
        gate1: {
          modelAccuracy: 0.6,
          baselineAccuracy: 0.5,
          deltaPp: 0.1,
          sampleSize: 42,
          evaluated: true,
          passed: true,
        },
        gate2: {
          modelRiskAdj: 0,
          baselineRiskAdj: 0,
          margin: 0,
          passed: false,
          evaluated: false,
        },
      },
    });
  }
  return rows;
}

/** Parse the `start`/`end` of a `Range: <start>-<end>` request header. */
function parseRange(header: string | undefined): { start: number; end: number } {
  // Default to the first page when the client sends no Range (defensive).
  if (header === undefined) {
    return { start: 0, end: PAGE_SIZE - 1 };
  }
  const [startText, endText] = header.split("-");
  return { start: Number(startText), end: Number(endText) };
}

/**
 * A no-network stub `fetch` modeling PostgREST for a single stored verdict whose
 * fold set has `total` rows. It:
 *   - returns the single aggregate row for the `id=eq.<id>&limit=1` select;
 *   - serves the fold select by honoring the `Range` request header: returns
 *     only `[start, end]` of the full fold set, sets a correct
 *     `Content-Range: start-end/total`, and replies 206 for a partial page
 *     (fewer than `total` rows) or 200 for a complete single page.
 */
function pagingFetch(total: number): typeof fetch {
  const aggregate = aggregateRow();
  const allFolds = foldRows(total);

  return ((url: string | URL, init?: RequestInit): Promise<Response> => {
    const target = String(url);
    const headers = (init?.headers ?? {}) as Record<string, string>;

    // Aggregate select: `gate_verdicts?id=eq.<id>&limit=1`.
    if (target.includes("/gate_verdicts?")) {
      return Promise.resolve(
        new Response(JSON.stringify([aggregate]), {
          status: 200,
          headers: {
            "Content-Type": "application/json",
            "Content-Range": `0-0/1`,
          },
        }),
      );
    }

    // Fold select: `gate_fold_verdicts?verdict_id=eq.<id>&order=fold_index.asc`.
    // Honor the Range header — this is where paging is exercised.
    const { start, end } = parseRange(headers.Range);
    const slice = allFolds.slice(start, Math.min(end + 1, total));
    const lastIndex = start + slice.length - 1;
    // 206 Partial Content whenever the slice does not cover the whole set.
    const partial = slice.length < total;
    return Promise.resolve(
      new Response(JSON.stringify(slice), {
        status: partial ? 206 : 200,
        headers: {
          "Content-Type": "application/json",
          "Content-Range": `${start}-${lastIndex < start ? start : lastIndex}/${total}`,
        },
      }),
    );
  }) as unknown as typeof fetch;
}

describe("SupabaseGateVerdictStore.getVerdict() paginated fold reads (Property 3)", () => {
  it("returns the complete fold set with no ~1000-row truncation across page boundaries", async () => {
    await fc.assert(
      fc.asyncProperty(
        // A fold count that always crosses at least one page boundary, capped
        // modestly so each iteration stays cheap while still paging > once.
        fc.integer({ min: PAGE_SIZE + 1, max: 2200 }),
        async (total) => {
          const store = new SupabaseGateVerdictStore(
            new SupabaseRestClient(CONFIG, pagingFetch(total)),
          );

          const persisted = await store.getVerdict(VERDICT_ID);

          // The verdict exists and carries its full fold set.
          expect(persisted).not.toBeNull();
          const folds = persisted!.verdict.foldVerdicts;

          // Every fold row is returned — no truncation at the ~1000 ceiling.
          expect(folds).toHaveLength(total);

          // The fold indices are complete and contiguous 0..total-1 in order,
          // i.e. no page was dropped or duplicated.
          for (let i = 0; i < total; i += 1) {
            expect(folds[i]?.foldIndex).toBe(i);
          }
        },
      ),
      { numRuns: 100 },
    );
  });
});
